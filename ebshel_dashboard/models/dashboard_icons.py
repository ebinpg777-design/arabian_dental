def normalize_icon(value):
    """The icon to store for ``value``: unchanged unless it is a FontAwesome one.

    Accepts the bare class (``fa-truck``) as well as the full one people paste
    from a 19.0 form (``fa fa-truck``, ``fa fa-fw fa-truck``). An empty value
    stays empty - the default applies at display time.
    """
    if not value or not isinstance(value, str):
        return value
    text = value.strip()
    if not text:
        return text
    names = [part for part in text.split() if part.startswith('fa-')
             and part not in ('fa-fw', 'fa-lg', 'fa-2x', 'fa-3x', 'fa-spin')]
    if not names and text.split()[0] != 'fa':
        return text
    for name in names:
        if name in FA_TO_ICON:
            return FA_TO_ICON[name]
    return FALLBACK_ICON


def is_icon(name):
    """Whether ``name`` is an icon the Odoo 20 fonts can draw."""
    return isinstance(name, str) and name in ICONS


def normalize_icon_vals(vals):
    """``vals`` with its ``icon`` (if any) translated, for create/write."""
    if vals.get('icon'):
        vals = dict(vals, icon=normalize_icon(vals['icon']))
    return vals
